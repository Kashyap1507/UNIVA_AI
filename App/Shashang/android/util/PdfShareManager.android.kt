package com.kashyap.wizlyai.util

import android.content.Context
import android.content.Intent
import android.graphics.Paint
import android.graphics.Typeface
import android.graphics.pdf.PdfDocument
import android.util.Log
import androidx.core.content.FileProvider
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.File
import java.io.FileOutputStream

/**
 * Android implementation of PdfShareManager
 * Generates and shares actual PDF files using Android PdfDocument API
 */
actual class PdfShareManager {

    companion object {
        private var appContext: Context? = null

        // PDF page dimensions (A4 size at 72 DPI)
        private const val PAGE_WIDTH = 595
        private const val PAGE_HEIGHT = 842
        private const val MARGIN = 40f
        private const val LINE_HEIGHT = 20f
        private const val TITLE_SIZE = 16f
        private const val BODY_SIZE = 12f

        /**
         * Initialize with application context
         * Call this from MainActivity.onCreate()
         */
        fun initialize(context: Context) {
            appContext = context.applicationContext
            Log.d("PdfShareManager", "Initialized with context")
        }
    }

    actual suspend fun sharePdf(content: String, fileName: String) = withContext(Dispatchers.Main) {
        val context = appContext ?: run {
            Log.e("PdfShareManager", "Context not initialized! Call PdfShareManager.initialize() first")
            return@withContext
        }

        try {
            // Ensure fileName has .pdf extension
            val pdfFileName = if (fileName.endsWith(".pdf")) fileName else "$fileName.pdf"

            Log.d("PdfShareManager", "Generating PDF file: $pdfFileName")

            // Create formatted content with header and footer
            val formattedContent = """
═══════════════════════════════════════
  WIZLY AI
═══════════════════════════════════════

$content

═══════════════════════════════════════
  Generated by Wizly AI
═══════════════════════════════════════
            """.trimIndent()

            // Generate PDF file
            val pdfFile = withContext(Dispatchers.IO) {
                generatePdfFile(context, pdfFileName, formattedContent)
            }

            if (pdfFile == null) {
                Log.e("PdfShareManager", "Failed to generate PDF file")
                return@withContext
            }

            Log.d("PdfShareManager", "PDF file created: ${pdfFile.absolutePath}")

            // Get shareable URI using FileProvider
            val fileUri = FileProvider.getUriForFile(
                context,
                "${context.packageName}.fileprovider",
                pdfFile
            )

            Log.d("PdfShareManager", "FileProvider URI: $fileUri")

            // Create share intent
            val shareIntent = Intent(Intent.ACTION_SEND).apply {
                type = "application/pdf"
                putExtra(Intent.EXTRA_STREAM, fileUri)
                putExtra(Intent.EXTRA_SUBJECT, pdfFileName.removeSuffix(".pdf"))
                addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
                addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
            }

            // Launch share sheet
            val chooser = Intent.createChooser(shareIntent, "Share PDF")
                .addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)

            context.startActivity(chooser)

            Log.d("PdfShareManager", "Share sheet launched successfully")

        } catch (e: Exception) {
            Log.e("PdfShareManager", "Failed to share PDF: ${e.message}", e)
        }
    }

    /**
     * Wraps text into lines that fit within the page width
     * Preserves existing line breaks and word boundaries
     */
    private fun wrapText(text: String, paint: Paint, maxWidth: Float): List<String> {
        val wrappedLines = mutableListOf<String>()
        val lines = text.split("\n")

        for (line in lines) {
            if (line.isEmpty()) {
                wrappedLines.add("")
                continue
            }

            // Measure the full line
            val lineWidth = paint.measureText(line)

            if (lineWidth <= maxWidth) {
                // Line fits, no wrapping needed
                wrappedLines.add(line)
            } else {
                // Line needs to be wrapped
                val words = line.split(" ")
                var currentLine = ""

                for (word in words) {
                    val testLine = if (currentLine.isEmpty()) word else "$currentLine $word"
                    val testWidth = paint.measureText(testLine)

                    if (testWidth <= maxWidth) {
                        // Word fits on current line
                        currentLine = testLine
                    } else {
                        // Word doesn't fit, start new line
                        if (currentLine.isNotEmpty()) {
                            wrappedLines.add(currentLine)
                        }

                        // Check if single word is too long
                        val wordWidth = paint.measureText(word)
                        if (wordWidth > maxWidth) {
                            // Break word into characters that fit
                            var charLine = ""
                            for (char in word) {
                                val testChar = "$charLine$char"
                                if (paint.measureText(testChar) <= maxWidth) {
                                    charLine = testChar
                                } else {
                                    if (charLine.isNotEmpty()) {
                                        wrappedLines.add(charLine)
                                    }
                                    charLine = char.toString()
                                }
                            }
                            currentLine = charLine
                        } else {
                            currentLine = word
                        }
                    }
                }

                // Add remaining text
                if (currentLine.isNotEmpty()) {
                    wrappedLines.add(currentLine)
                }
            }
        }

        return wrappedLines
    }

    /**
     * Generates a PDF file from text content using Android PdfDocument API
     */
    private fun generatePdfFile(context: Context, fileName: String, content: String): File? {
        return try {
            // Create a new PDF document
            val pdfDocument = PdfDocument()

            // Prepare text paint
            val textPaint = Paint().apply {
                textSize = BODY_SIZE
                typeface = Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
                isAntiAlias = true
            }

            // Calculate maximum text width (page width minus margins)
            val maxTextWidth = PAGE_WIDTH - (MARGIN * 2)

            // Wrap text into lines that fit within page width
            val lines = wrapText(content, textPaint, maxTextWidth)
            var currentY = MARGIN
            var pageNumber = 1

            // Start first page
            var pageInfo = PdfDocument.PageInfo.Builder(PAGE_WIDTH, PAGE_HEIGHT, pageNumber).create()
            var page = pdfDocument.startPage(pageInfo)
            var canvas = page.canvas

            // Draw each line
            for (line in lines) {
                // Check if we need a new page
                if (currentY + LINE_HEIGHT > PAGE_HEIGHT - MARGIN) {
                    // Finish current page
                    pdfDocument.finishPage(page)

                    // Start new page
                    pageNumber++
                    pageInfo = PdfDocument.PageInfo.Builder(PAGE_WIDTH, PAGE_HEIGHT, pageNumber).create()
                    page = pdfDocument.startPage(pageInfo)
                    canvas = page.canvas
                    currentY = MARGIN
                }

                // Draw the line
                canvas.drawText(line, MARGIN, currentY, textPaint)
                currentY += LINE_HEIGHT
            }

            // Finish last page
            pdfDocument.finishPage(page)

            // Save PDF to file
            val file = File(context.cacheDir, fileName)
            FileOutputStream(file).use { outputStream ->
                pdfDocument.writeTo(outputStream)
            }

            // Close the document
            pdfDocument.close()

            Log.d("PdfShareManager", "PDF generated successfully: ${file.absolutePath}")
            file

        } catch (e: Exception) {
            Log.e("PdfShareManager", "Error generating PDF: ${e.message}", e)
            null
        }
    }
}
