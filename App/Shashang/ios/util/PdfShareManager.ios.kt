package com.kashyap.wizlyai.util

import kotlinx.cinterop.*
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import platform.CoreGraphics.CGRectMake
import platform.Foundation.*
import platform.UIKit.*

/**
 * iOS implementation of PdfShareManager
 * Generates and shares actual PDF files using UIKit PDF APIs
 */
@OptIn(ExperimentalForeignApi::class)
actual class PdfShareManager {

    companion object {
        // PDF page dimensions (A4 size at 72 DPI)
        private const val PAGE_WIDTH = 595.0
        private const val PAGE_HEIGHT = 842.0
        private const val MARGIN = 40.0
        private const val LINE_HEIGHT = 20.0
        private const val FONT_SIZE = 12.0
    }

    actual suspend fun sharePdf(content: String, fileName: String) = withContext(Dispatchers.Main) {
        try {
            // Ensure fileName has .pdf extension
            val pdfFileName = if (fileName.endsWith(".pdf")) fileName else "$fileName.pdf"

            println("ℹ️ IOSPdfShareManager: Generating PDF file: $pdfFileName")

            // Create formatted content with header and footer
            val formattedContent = """
═══════════════════════════════════════
  WIZLY AI
═══════════════════════════════════════

$content

═══════════════════════════════════════
  Generated by Wizly AI
═══════════════════════════════════════
            """.trimIndent()

            // Generate PDF data
            val pdfData = generatePdfData(formattedContent)

            if (pdfData == null) {
                println("❌ Failed to generate PDF data")
                return@withContext
            }

            // Save to temporary directory
            val tempDir = NSFileManager.defaultManager.temporaryDirectory
            val fileURL = tempDir.URLByAppendingPathComponent(pdfFileName)

            if (fileURL == null) {
                println("❌ Failed to create temporary file URL")
                return@withContext
            }

            // Write PDF data to file
            val success = pdfData.writeToURL(fileURL, atomically = true)

            if (!success) {
                println("❌ Failed to write PDF file")
                return@withContext
            }

            println("✅ PDF file created: ${fileURL.path}")

            // Share via UIActivityViewController
            shareFile(fileURL)

        } catch (e: Exception) {
            println("❌ IOSPdfShareManager: Failed to share PDF: ${e.message}")
            e.printStackTrace()
        }
    }

    /**
     * Wraps text into lines that fit within the page width
     * Preserves existing line breaks and word boundaries
     */
    private fun wrapText(text: String, font: UIFont, maxWidth: Double): List<String> {
        val wrappedLines = mutableListOf<String>()
        val lines = text.split("\n")

        val textAttributes = mapOf<Any?, Any?>(
            NSFontAttributeName to font
        )

        for (line in lines) {
            if (line.isEmpty()) {
                wrappedLines.add("")
                continue
            }

            // Measure the full line
            val nsLine = line as NSString
            val lineSize = nsLine.sizeWithAttributes(textAttributes)
            val lineWidth = lineSize.useContents { this.width }

            if (lineWidth <= maxWidth) {
                // Line fits, no wrapping needed
                wrappedLines.add(line)
            } else {
                // Line needs to be wrapped
                val words = line.split(" ")
                var currentLine = ""

                for (word in words) {
                    val testLine = if (currentLine.isEmpty()) word else "$currentLine $word"
                    val nsTestLine = testLine as NSString
                    val testSize = nsTestLine.sizeWithAttributes(textAttributes)
                    val testWidth = testSize.useContents { this.width }

                    if (testWidth <= maxWidth) {
                        // Word fits on current line
                        currentLine = testLine
                    } else {
                        // Word doesn't fit, start new line
                        if (currentLine.isNotEmpty()) {
                            wrappedLines.add(currentLine)
                        }

                        // Check if single word is too long
                        val nsWord = word as NSString
                        val wordSize = nsWord.sizeWithAttributes(textAttributes)
                        val wordWidth = wordSize.useContents { this.width }

                        if (wordWidth > maxWidth) {
                            // Break word into characters that fit
                            var charLine = ""
                            for (char in word) {
                                val testChar = "$charLine$char"
                                val nsTestChar = testChar as NSString
                                val testCharSize = nsTestChar.sizeWithAttributes(textAttributes)
                                val testCharWidth = testCharSize.useContents { this.width }

                                if (testCharWidth <= maxWidth) {
                                    charLine = testChar
                                } else {
                                    if (charLine.isNotEmpty()) {
                                        wrappedLines.add(charLine)
                                    }
                                    charLine = char.toString()
                                }
                            }
                            currentLine = charLine
                        } else {
                            currentLine = word
                        }
                    }
                }

                // Add remaining text
                if (currentLine.isNotEmpty()) {
                    wrappedLines.add(currentLine)
                }
            }
        }

        return wrappedLines
    }

    /**
     * Generates PDF data from text content using UIKit PDF APIs
     */
    private fun generatePdfData(content: String): NSData? {
        return try {
            // Create PDF in memory
            val pdfData = NSMutableData()

            // Set up page dimensions
            val pageRect = CGRectMake(0.0, 0.0, PAGE_WIDTH, PAGE_HEIGHT)

            // Begin PDF context writing to data
            UIGraphicsBeginPDFContextToData(pdfData, pageRect, null)

            // Create text attributes for drawing
            val font = UIFont.systemFontOfSize(FONT_SIZE)
            val paragraphStyle = NSMutableParagraphStyle()
            paragraphStyle.setLineSpacing(4.0)

            val textAttributes = mapOf<Any?, Any?>(
                NSFontAttributeName to font,
                NSParagraphStyleAttributeName to paragraphStyle
            )

            // Calculate maximum text width (page width minus margins)
            val maxTextWidth = PAGE_WIDTH - (MARGIN * 2)

            // Wrap text into lines that fit within page width
            val lines = wrapText(content, font, maxTextWidth)
            var currentY = MARGIN

            // Begin first page
            UIGraphicsBeginPDFPageWithInfo(pageRect, null)

            // Draw each line
            for (line in lines) {
                // Check if we need a new page
                if (currentY + LINE_HEIGHT > PAGE_HEIGHT - MARGIN) {
                    // Start new page
                    UIGraphicsBeginPDFPageWithInfo(pageRect, null)
                    currentY = MARGIN
                }

                // Draw the line
                val textRect = CGRectMake(MARGIN, currentY, maxTextWidth, LINE_HEIGHT)
                val nsString = line as NSString
                nsString.drawInRect(textRect, textAttributes)

                currentY += LINE_HEIGHT
            }

            // End PDF context
            UIGraphicsEndPDFContext()

            println("✅ PDF generated successfully (${pdfData.length} bytes)")
            pdfData

        } catch (e: Exception) {
            println("❌ Error generating PDF: ${e.message}")
            e.printStackTrace()
            null
        }
    }

    /**
     * Share a file using UIActivityViewController
     */
    private fun shareFile(fileURL: NSURL) {
        try {
            println("ℹ️ Presenting share sheet for: ${fileURL.path}")

            // Get the root view controller
            val scenes = UIApplication.sharedApplication.connectedScenes
            val scenesList = scenes.toList() as? List<*>
            val windowScene = scenesList?.firstOrNull { it is UIWindowScene } as? UIWindowScene

            if (windowScene == null) {
                println("❌ No window scene found")
                return
            }

            val window = windowScene.windows.firstOrNull() as? UIWindow
            if (window == null) {
                println("❌ No window found")
                return
            }

            val rootViewController = window.rootViewController
            if (rootViewController == null) {
                println("❌ No root view controller found")
                return
            }

            // Find the top-most view controller
            var topController: UIViewController = rootViewController
            var presented = topController.presentedViewController
            while (presented != null) {
                topController = presented
                presented = topController.presentedViewController
            }

            println("✓ Found top view controller, presenting share sheet...")

            // Create UIActivityViewController
            val activityViewController = UIActivityViewController(
                activityItems = listOf(fileURL),
                applicationActivities = null
            )

            // For iPad - set popover presentation
            val popover = activityViewController.popoverPresentationController
            if (popover != null) {
                popover.sourceView = topController.view
                popover.sourceRect = topController.view.bounds
            }

            // Present the share sheet
            topController.presentViewController(
                activityViewController,
                animated = true,
                completion = null
            )

            println("✅ Share sheet presented successfully")

        } catch (e: Exception) {
            println("❌ Failed to present share sheet: ${e.message}")
            e.printStackTrace()
        }
    }
}
